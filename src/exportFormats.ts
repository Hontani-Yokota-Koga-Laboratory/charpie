/** `images` resolves image shapes' `src=` (exports pass data: URIs so the file stands alone). */
export function exportSvg(layout: Layout, bg: string | null = '#ffffff', images?: ImageHref): string {
  return '<?xml version="1.0" encoding="UTF-8"?>\n' + renderToStaticMarkup(createElement(DiagramSvg, { layout, bg, images }));
}

/**
 * Prefix every `id=` of an SVG (and the `#id` references to it). Each page is rendered on its own,
 * so their ids (clip paths of embedded diagrams, …) repeat; once several pages share one document
 * (PDF), a reference would otherwise pick up another page's definition.
 */
export function scopeIds(svg: string, prefix: string): string {
  const ids = new Set([...svg.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]));
  if (!ids.size) return svg;
  return svg
    .replace(/(\sid=")([^"]+)"/g, (_, open: string, id: string) => `${open}${prefix}${id}"`)
    .replace(/(url\(#|href="#)([^)"]+)/g, (all, open: string, id: string) => (ids.has(id) ? open + prefix + id : all));
}

/** Distinct `src=` of the image shapes in a layout. */
export function imageSources(layout: Layout): string[] {
  // pictures inside embedded diagrams too (their src is already relative to this file)
  const all = (l: Layout): string[] => l.nodes.flatMap((n) => (n.embed ? all(n.embed.layout) : n.kind === 'image' && n.style.src && !isDiagramSrc(n.style.src) ? [n.style.src] : []));
  return [...new Set(all(layout))];
}

// ───────────── TikZ ─────────────

const PX = 0.75; // 1px = 0.75pt
const f = (n: number) => String(Math.round(n * PX * 100) / 100);

function texEscape(s: string): string {
  return s.replace(/[\\{}$&#^_%~]/g, (c) => ({ '\\': '\\textbackslash{}', '~': '\\textasciitilde{}', '^': '\\textasciicircum{}' })[c] ?? '\\' + c);
}

/** A label line for TeX: formulas go through as `$...$`, `**bold**` becomes \textbf, the rest is escaped. */
const texLine = (l: string) =>
  splitInline(l)
    .map((g) => {
      const t = g.math ? `$${g.s}$` : texEscape(g.s);
      return g.bold && t ? `\\textbf{${t}}` : t;
    })
    .join('');

/** Every `family=` in a layout (embedded diagrams too). */
function familiesOf(layout: Layout, out = new Set<string>()): Set<string> {
  for (const n of layout.nodes) {
    if (n.style.family) out.add(n.style.family);
    if (n.embed) familiesOf(n.embed.layout, out);
  }
  for (const e of layout.edges) if (e.style.family) out.add(e.style.family);
  return out;
}

/** TeX command that selects a family (latin + Japanese): `M PLUS 1p` → `\cpfMPLUSbp`. */
const fontCmd = (family: string) => '\\cpf' + family.replace(/[0-9]/g, (d) => 'abcdefghij'[Number(d)]).replace(/[^A-Za-z]/g, '');

/** fontspec / luatexja-fontspec definitions for the families (the fonts must be installed for lualatex). */
function fontDefs(families: Set<string>): string[] {
  return [...families].flatMap((fam) => {
    const c = fontCmd(fam);
    return [`\\newfontfamily${c}L{${fam}}`, `\\newjfontfamily${c}J{${fam}}`, `\\newcommand*${c}{${c}L${c}J}`];
  });
}

export function exportTikz(layout: Layout): string {
  return tikzParts(layout, true).join('\n') + '\n';
}

/**
 * A whole deck as one LaTeX document, one page per slide at the slide's size
 * (lualatex; luatexja for Japanese).
 */
export function exportTikzDeck(pages: Layout[]): string {
  const page = pages[0]?.frame ?? { x: 0, y: 0, w: 1280, h: 720 };
  const usesImages = pages.some((l) => imageSources(l).length);
  const families = new Set<string>();
  for (const l of pages) familiesOf(l, families);
  return [
    '% Generated by Charpie — one page per slide. Compile with lualatex.',
    '\\documentclass{article}',
    `\\usepackage[paperwidth=${f(page.w)}pt, paperheight=${f(page.h)}pt, margin=0pt]{geometry}`,
    families.size ? '\\usepackage{luatexja-fontspec}  % family= fonts (installed on this machine) + Japanese' : '\\usepackage{luatexja}  % Japanese (remove if the slides have none)',
    '\\usepackage{tikz}' + (usesImages ? '\n\\usepackage{graphicx}' : ''),
    ...fontDefs(families),
    '\\pagestyle{empty}',
    '\\setlength{\\parindent}{0pt}',
    '\\begin{document}',
    ...pages.flatMap((l, i) => [`% ── page ${i + 1}`, ...tikzParts(l).slice(1), ...(i < pages.length - 1 ? ['\\newpage'] : [])]),
    '\\end{document}',
    '',
  ].join('\n');
}

function tikzParts(layout: Layout, withFonts = false): string[] {
  const { defs, body } = tikzBody(layout, 'cp');
  const families = withFonts ? familiesOf(layout) : new Set<string>();
  // a page keeps its size (and what is outside it is cut off), whatever is drawn on it
  const fr = layout.frame;
  const page = fr ? [`  \\useasboundingbox (${f(fr.x)},${f(-fr.y)}) rectangle (${f(fr.x + fr.w)},${f(-(fr.y + fr.h))});`, `  \\clip (${f(fr.x)},${f(-fr.y)}) rectangle (${f(fr.x + fr.w)},${f(-(fr.y + fr.h))});`] : [];
  return [
    '% Generated by Charpie — requires \\usepackage{tikz} (and xcolor' + (imageSources(layout).length ? ', graphicx' : '') + (families.size ? ', luatexja-fontspec' : '') + ')',
    ...fontDefs(families),
    ...defs,
    '\\begin{tikzpicture}[x=1pt, y=1pt]',
    ...page,
    ...body,
    '\\end{tikzpicture}',
  ];
}

/** Colour definitions and drawing commands; `prefix` keeps the colour names of embedded diagrams apart. */
function tikzBody(layout: Layout, prefix: string): { defs: string[]; body: string[] } {
  const colors = new Map<string, string>();
  const color = (c: string): string | undefined => {
    if (!c || c === 'none') return undefined;
    let hex = c.replace('#', '').toUpperCase();
    if (!/^[0-9A-F]+$/.test(hex)) return c; // named color: pass through
    if (hex.length === 3 || hex.length === 4) hex = [...hex.slice(0, 3)].map((x) => x + x).join('');
    hex = hex.slice(0, 6);
    if (!colors.has(hex)) colors.set(hex, `${prefix}${colors.size + 1}`);
    return colors.get(hex)!;
  };
  const fam = (family: string | undefined) => (family ? fontCmd(family) : '');
  const dash = (d: string) => (d === 'dashed' ? ', dashed' : d === 'dotted' ? ', dotted' : '');
  const body: string[] = [];

  for (const n of layout.nodes) {
    const s = n.style;
    const draw = color(s.stroke);
    const fill = color(s.fill);
    const frame = n.kind === 'table' ? undefined : draw;
    const opts = [frame ? `draw=${frame}` : 'draw=none', fill ? `fill=${fill}` : null, `line width=${f(s.lw)}pt`].filter(Boolean).join(', ') + dash(s.dash) + (n.kind === 'round' ? `, rounded corners=${f(s.radius)}pt` : '');
    const { x, y, w, h } = n.box;
    let shape: string;
    if (n.kind === 'ellipse' || n.kind === 'cross' || n.kind === 'plus') shape = `(${f(x + w / 2)},${f(-(y + h / 2))}) ellipse [x radius=${f(w / 2)}pt, y radius=${f(h / 2)}pt]`;
    else if (n.kind === 'rect' || n.kind === 'round' || n.kind === 'text') shape = `(${f(x)},${f(-y)}) rectangle (${f(x + w)},${f(-(y + h))})`;
    else shape = n.poly.map((p) => `(${f(p.x)},${f(-p.y)})`).join(' -- ') + ' -- cycle';
    body.push(`  % ${n.id}`);
    if (n.embed) {
      // another diagram: drawn at its own coordinates, shifted and scaled into the box (text scales too)
      const e = n.embed;
      const inner = tikzBody(e.layout, `${prefix}${n.id.replace(/[^A-Za-z]/g, '') || 'e'}x`);
      body.push(`  % ${n.id}: ${s.src}`, '  \\begin{scope}', `  \\clip (${f(x)},${f(-y)}) rectangle (${f(x + w)},${f(-(y + h))});`, `  \\begin{scope}[shift={(${f(e.dx)},${f(-e.dy)})}, scale=${+e.scale.toFixed(4)}, transform shape]`);
      body.push(...inner.defs.map((d) => '  ' + d), ...inner.body.map((l) => '  ' + l), '  \\end{scope}', '  \\end{scope}');
    } else if (n.kind === 'image' && isDiagramSrc(s.src)) body.push(`  % ${n.id}: ${s.src} (not found)`);
    else if (n.kind === 'image' && s.src) {
      // path relative to the .charpie file; keep it next to the .tex (needs \usepackage{graphicx})
      const keep = s.fit === 'fill' ? '' : ', keepaspectratio';
      body.push(`  \\node[anchor=center, inner sep=0pt] at (${f(x + w / 2)},${f(-(y + h / 2))}) {\\includegraphics[width=${f(w)}pt, height=${f(h)}pt${keep}]{${s.src}}};`);
    }
    if (frame || fill) body.push(`  \\path[${opts}] ${shape};`);
    if (n.blocks) {
      // table rules and the text pieces of tables / lists
      const rc = color(s.stroke) ?? color(s.text);
      for (const b of n.blocks.fills) {
        const fc = color(b.fill);
        if (fc) body.push(`  \\fill[${fc}] (${f(b.x)},${f(-b.y)}) rectangle (${f(b.x + b.w)},${f(-(b.y + b.h))});`);
      }
      const mc = color(s.text) ?? 'black';
      for (const m of n.blocks.marks) {
        if (m.kind === 'square') body.push(`  \\fill[${mc}] (${f(m.cx - m.r)},${f(-(m.cy - m.r))}) rectangle (${f(m.cx + m.r)},${f(-(m.cy + m.r))});`);
        else if (m.kind === 'circle') body.push(`  \\draw[${mc}, line width=${f(m.r * 0.28)}pt] (${f(m.cx)},${f(-m.cy)}) circle (${f(m.r * 0.86)}pt);`);
        else body.push(`  \\fill[${mc}] (${f(m.cx)},${f(-m.cy)}) circle (${f(m.r)}pt);`);
      }
      for (const r of n.blocks.rules) body.push(`  \\draw[${rc ? `draw=${rc}, ` : ''}line width=${f(r.lw)}pt] (${f(r.x1)},${f(-r.y1)}) -- (${f(r.x2)},${f(-r.y2)});`);
      for (const p of n.blocks.pieces) {
        const tc = color(p.color ?? s.text);
        const size = p.size * PX;
        const lh = p.lh ?? LINE_HEIGHT;
        const font = `font=${fam(s.family)}\\fontsize{${size.toFixed(1)}}{${(size * lh).toFixed(1)}}\\selectfont${p.weight >= 600 ? '\\bfseries' : ''}`;
        const anchor = p.anchor === 'left' ? 'north west' : p.anchor === 'right' ? 'north east' : 'north';
        // a taller line box puts its extra space half above the first line
        const top = p.y + ((lh - LINE_HEIGHT) * p.size) / 2;
        body.push(`  \\node[align=${p.anchor}, anchor=${anchor}, inner sep=0pt${tc ? `, text=${tc}` : ''}, ${font}] at (${f(p.x)},${f(-top)}) {${p.lines.map(texLine).join('\\\\ ')}};`);
      }
    }
    if (draw && (n.kind === 'cross' || n.kind === 'plus'))
      for (const [p, q] of junctionStrokes(n.kind, n.box)) body.push(`  \\draw[draw=${draw}, line width=${f(s.lw)}pt] (${f(p.x)},${f(-p.y)}) -- (${f(q.x)},${f(-q.y)});`);
    if (n.def.label && n.kind !== 'image' && !n.blocks) {
      const tc = color(s.text);
      const size = n.text.size * PX;
      const lines = n.text.lines.map(texLine).join('\\\\ ');
      const font = `font=${fam(s.family)}\\fontsize{${size.toFixed(1)}}{${(size * LINE_HEIGHT).toFixed(1)}}\\selectfont${s.weight >= 600 ? '\\bfseries' : ''}`;
      const cy = n.textRect.y + n.textRect.h / 2;
      if (s.rotate === 0) {
        body.push(
          `  \\node[align=${s.halign}, anchor=${s.halign === 'left' ? 'west' : s.halign === 'right' ? 'east' : 'center'}, inner sep=0pt${tc ? `, text=${tc}` : ''}, ${font}] at (${f(s.halign === 'left' ? n.textBox.x : s.halign === 'right' ? n.textBox.x + n.textBox.w : n.textBox.x + n.textBox.w / 2)},${f(-cy)}) {${lines}};`,
        );
      } else {
        // TikZ rotates counter-clockwise; ours is clockwise on a y-down canvas
        const cx = n.textRect.x + n.textRect.w / 2;
        body.push(`  \\node[align=${lineAnchor(s)}, anchor=center, rotate=${-s.rotate}, inner sep=0pt${tc ? `, text=${tc}` : ''}, ${font}] at (${f(cx)},${f(-cy)}) {${lines}};`);
      }
    }
  }

  for (const e of layout.edges) {
    const s = e.style;
    const c = color(s.stroke);
    body.push(`  % ${e.def.from} ${e.def.op} ${e.def.to}`);
    const pts = e.pts.map((p) => `(${f(p.x)},${f(-p.y)})`).join(' -- ');
    body.push(`  \\draw[${c ? `draw=${c}` : ''}, line width=${f(s.lw)}pt${dash(s.dash)}${e.style.route === 'ortho' ? ', rounded corners=4pt' : ''}] ${pts};`);
    for (const hd of e.heads) {
      const path = arrowHeadPath(hd, s.lw)
        .replace(/^M/, '')
        .replace(/Z$/, '')
        .split('L')
        .map((pair) => {
          const [px, py] = pair.trim().split(/\s+/).map(Number);
          return `(${f(px)},${f(-py)})`;
        })
        .join(' -- ');
      body.push(`  \\fill[${c ?? 'black'}] ${path} -- cycle;`);
    }
    if (e.label) {
      const tc = color(s.text);
      const size = e.label.size * PX;
      body.push(
        `  \\node[fill=white, rounded corners=2pt, inner sep=2pt, align=center${tc ? `, text=${tc}` : ''}, font=${fam(s.family)}\\fontsize{${size.toFixed(1)}}{${(size * LINE_HEIGHT).toFixed(1)}}\\selectfont] at (${f(e.label.center.x)},${f(-e.label.center.y)}) {${e.label.lines.map(texLine).join('\\\\ ')}};`,
      );
    }
  }

  const defs = [...colors.entries()].map(([hex, name]) => `\\definecolor{${name}}{HTML}{${hex}}`);
  return { defs, body };
}

